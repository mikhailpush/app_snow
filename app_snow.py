def compute_class_quorum_board(df: pd.DataFrame) -> pd.DataFrame:
    cdf = df.copy()
    cdf["Score"] = pd.to_numeric(cdf["Score"], errors="coerce").fillna(0).astype(int)
    cdf["TimeSec"] = pd.to_numeric(cdf["TimeSec"], errors="coerce").fillna(9999).astype(int)
    cdf = cdf.sort_values(by=["Grade", "Score", "TimeSec"], ascending=[True, False, True])

    rows = []
    for grade, grp in cdf.groupby("Grade"):
        total_players = len(grp)
        top_n = grp.head(QUORUM_SIZE)
        q_count = len(top_n)
        q_sum = int(top_n["Score"].sum())
        q_avg = round(float(top_n["Score"].mean()), 1)
        q_time = int(top_n["TimeSec"].sum())
        status = f"✅ {q_count}/{QUORUM_SIZE} (Кворум собран)" if total_players >= QUORUM_SIZE else f"⏳ {q_count}/{QUORUM_SIZE} (Сбор команды)"
        rows.append({
            "Класс": grade,
            "Статус кворума (ТОП-10)": status,
            "Всего прошло": total_players,
            "Зачет ТОП-10 (из 1000)": q_sum,
            "Средний балл ТОП-10": q_avg,
            "Суммарное время ТОП-10 (с)": q_time
        })
    res = pd.DataFrame(rows)
    res = res.sort_values(
        by=["Зачет ТОП-10 (из 1000)", "Суммарное время ТОП-10 (с)"],
        ascending=[False, True]
    ).reset_index(drop=True)
    res.index += 1
    return res

